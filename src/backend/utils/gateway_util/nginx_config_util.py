"""Generate the Nginx snippets that route public traffic to services.

The backend owns the routing table; this module is a pure string builder so it
can be unit-tested without Nginx or a database.
"""
from typing import Iterable
from urllib.parse import urlsplit


def build_server_name(slug: str, base_domain: str) -> str:
    """Return an Nginx server_name value for a service.

    ``localhost`` is the development default. Using a regex there keeps local
    ``*.localhost`` working while also matching a real public tunnel hostname
    before the operator has configured a production base domain.
    """
    domain = str(base_domain or "").strip().strip(".")
    if domain and domain != "localhost":
        # Keep the loopback name alongside the production domain so local
        # console links (*.localhost) continue to work after setting a domain.
        return f"{slug}.{domain} {slug}.localhost"
    return f"~^{slug}\\..+$"


def build_proxy_lines(target_url: str, settings: dict, indent: str) -> str:
    """Build the shared reverse-proxy directives for one service."""
    parsed = urlsplit(target_url)
    scheme = settings.get("public_scheme", "http")
    is_https = parsed.scheme == "https"
    lines = [
        "proxy_http_version 1.1;",
        "proxy_set_header Host $host;",
        "proxy_set_header X-Real-IP $remote_addr;",
        "proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
        f"proxy_set_header X-Forwarded-Proto {scheme};",
        "proxy_set_header X-Forwarded-Host $host;",
        "proxy_set_header Upgrade $http_upgrade;",
        "proxy_set_header Connection $connection_upgrade;",
        "proxy_read_timeout 3600s;",
        "proxy_send_timeout 3600s;",
        "proxy_buffering off;",
        "proxy_hide_header X-Frame-Options;",
        "proxy_hide_header Content-Security-Policy;",
        "proxy_hide_header Permissions-Policy;",
    ]
    if is_https:
        lines.append("proxy_ssl_server_name on;")
        verify = "off" if settings.get("skip_tls_verify") else "on"
        lines.append(f"proxy_ssl_verify {verify};")
    return "\n".join(f"{indent}{line}" for line in lines)


def build_hosts_config(services: Iterable, settings: dict) -> str:
    """Build the per-service ``server`` blocks included in the http context."""
    blocks = [
        "# Generated by XiLiServerSwitchManageSystem. Do not edit manually.",
        "# This file is reloaded by the gateway watcher.",
        "",
    ]
    for service in services:
        if not service.is_enabled:
            continue
        # Direct-origin services are reached at their own URL; no route at all.
        if getattr(service, "mode", "auto") == "origin":
            continue
        server_name = build_server_name(service.slug, settings.get("base_domain", ""))
        proxy_lines = build_proxy_lines(service.target_url, settings, "        ")
        blocks.extend(
            [
                "server {",
                "    listen 80;",
                f"    server_name {server_name};",
                "    resolver 127.0.0.11 valid=10s ipv6=off;",
                "    client_max_body_size 500m;",
                "",
                "    location / {",
                f"        set $svc_upstream {service.target_url};",
                "        proxy_pass $svc_upstream;",
                proxy_lines,
                "    }",
                "}",
                "",
            ]
        )
    if len(blocks) == 3:
        blocks.append("# No enabled services.")
    return "\n".join(blocks).rstrip() + "\n"


def build_paths_config(services: Iterable, settings: dict) -> str:
    """Build the ``location`` blocks included in the panel server."""
    blocks = [
        "# Generated by XiLiServerSwitchManageSystem. Do not edit manually.",
        "# Path mode is a compatibility fallback; subdomain mode is preferred.",
        "",
    ]
    for service in services:
        if not service.is_enabled:
            continue
        # Direct-origin services are reached at their own URL; no route at all.
        if getattr(service, "mode", "auto") == "origin":
            continue
        prefix = f"/p/{service.slug}"
        proxy_lines = build_proxy_lines(service.target_url, settings, "        ")
        strip_prefix = getattr(service, "strip_prefix", True)
        location_lines = [
            f"location = {prefix} {{",
            f"    return 308 {prefix}/;",
            "}",
            f"location ^~ {prefix}/ {{",
            # `set` must run before `rewrite ... break`: break stops the
            # rewrite phase, so a later set would be skipped.
            f"    set $svc_upstream {service.target_url};",
        ]
        if strip_prefix:
            location_lines.extend(
                [
                    f"    rewrite ^{prefix}/(.*)$ /$1 break;",
                    # The app sees a stripped path, so absolute redirects and
                    # cookie paths it emits must be mapped back onto the mount
                    # point. X-Forwarded-Prefix lets aware apps build URLs too.
                    # Match relative and absolute Location headers; emit a
                    # relative prefixed path so the browser stays on the public
                    # origin instead of the upstream's internal host.
                    f"    proxy_redirect ~^(?:https?://[^/]+)?(?!/p/)(/.*)$ {prefix}$1;",
                    f"    proxy_cookie_path / {prefix}/;",
                    f"    proxy_set_header X-Forwarded-Prefix {prefix};",
                ]
            )
        location_lines.extend(
            [
                "    proxy_pass $svc_upstream;",
                proxy_lines,
                "}",
                "",
            ]
        )
        blocks.extend(location_lines)
    if len(blocks) == 3:
        blocks.append("# No path services.")
    return "\n".join(blocks).rstrip() + "\n"
