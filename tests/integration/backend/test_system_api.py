"""Integration tests for settings, gateway and audit endpoints."""


class TestSystemInfo:
    """System overview endpoint."""

    def test_info_requires_token(self, client):
        assert client.get("/api/system/info").status_code == 401

    def test_info_contains_gateway_and_stats(self, client, auth_headers):
        response = client.get("/api/system/info", headers=auth_headers)
        assert response.status_code == 200
        data = response.get_json()["data"]
        assert data["settings"]["base_domain"] == "localhost"
        assert data["gateway"]["synced"] is True
        assert data["stats"]["total"] == 0


class TestSettings:
    """Settings validation and gateway regeneration."""

    def test_get_settings(self, client, auth_headers):
        response = client.get("/api/system/settings", headers=auth_headers)
        assert response.status_code == 200
        assert response.get_json()["data"]["public_scheme"] == "http"

    def test_update_settings_regenerates_gateway(self, client, auth_headers):
        response = client.put(
            "/api/system/settings",
            headers=auth_headers,
            json={
                "base_domain": "example.com",
                "public_scheme": "https",
                "public_port": "",
                "health_interval": 30,
                "skip_tls_verify": False,
                "site_name": "XiLiServerSwitchManageSystem Test",
            },
        )
        assert response.status_code == 200
        data = response.get_json()["data"]
        assert data["settings"]["base_domain"] == "example.com"
        assert data["gateway"]["synced"] is True

    def test_update_settings_rejects_bad_port(self, client, auth_headers):
        response = client.put(
            "/api/system/settings",
            headers=auth_headers,
            json={"public_port": "99999"},
        )
        assert response.status_code == 400

    def test_settings_requires_admin(self, client, auth_headers):
        assert client.put("/api/system/settings", json={"site_name": "x"}).status_code == 401
        assert client.put("/api/system/settings", headers=auth_headers, json={"site_name": "x"}).status_code == 200


class TestGatewayAndAudit:
    """Gateway sync, config preview and audit stream."""

    def test_sync_gateway(self, client, auth_headers):
        response = client.post("/api/system/gateway/sync", headers=auth_headers)
        assert response.status_code == 200
        assert response.get_json()["data"]["synced"] is True

    def test_gateway_config_preview(self, client, auth_headers):
        response = client.get("/api/system/gateway/config", headers=auth_headers)
        assert response.status_code == 200
        data = response.get_json()["data"]
        assert "Generated by XiLiServerSwitchManageSystem" in data["hosts"]
        assert "Generated by XiLiServerSwitchManageSystem" in data["paths"]

    def test_audit_logs_include_login(self, client, auth_headers):
        response = client.get("/api/system/audit-logs?limit=5", headers=auth_headers)
        assert response.status_code == 200
        logs = response.get_json()["data"]["logs"]
        assert any(log["action"] == "auth.login" for log in logs)
